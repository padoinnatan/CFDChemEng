clear; clc; close all;

%% ===================== DATA =====================

% -------- Experimental --------
x = [100 200 300 400 500];              % Reynolds (example)
y = [0.20 0.25 0.28 0.30 0.32];         % Effectiveness

% -------- CFD (Simulated) --------
Re = [100 200 300 400 500];
ef = [0.22 0.26 0.29 0.31 0.33];

% -------- Analytical --------
xj = [100 200 300 400 500];
yj = [0.21 0.255 0.285 0.305 0.325];

%% ===================== PLOT =====================

figure('Color','w','Position',[300 300 800 600])
hold on

% -------- Experimental --------
plot(x, y, 'o', ...
    'MarkerSize', 10, ...
    'LineWidth', 2, ...
    'MarkerFaceColor', [0 0.4470 0.7410], ...
    'MarkerEdgeColor', [0 0.4470 0.7410]);

% -------- CFD --------
plot(Re, ef, 's', ...
    'MarkerSize', 10, ...
    'LineWidth', 2, ...
    'MarkerFaceColor', [0.8500 0.3250 0.0980], ...
    'MarkerEdgeColor', [0.8500 0.3250 0.0980]);

% -------- Analytical --------
plot(xj, yj, 'd', ...
    'MarkerSize', 10, ...
    'LineWidth', 2, ...
    'MarkerFaceColor', [0.4660 0.6740 0.1880], ...
    'MarkerEdgeColor', [0.4660 0.6740 0.1880]);

%% ===================== AXES =====================

xlabel('$\mathrm{Re}$', ...
    'Interpreter','latex', ...
    'FontSize', 32)

ylabel('$\varepsilon$', ...
    'Interpreter','latex', ...
    'FontSize', 32)

grid on
box on

set(gca, ...
    'FontSize', 18, ...
    'TickLabelInterpreter', 'latex', ...
    'LineWidth', 1.2)

ax = gca;
ax.YAxis.TickLabelFormat = '%.2f';

ylim([0.15 0.35])

%% ===================== LEGEND =====================

legend({'Experimental','CFD','Analytical'}, ...
    'Interpreter','latex', ...
    'Location','best', ...
    'FontSize', 16);
